// Package scheduler provides the run-owned admission broker for physical HTTP
// attempts.  It deliberately has no transport dependency: callers hold a
// Lease until a response body, stream, or cancelled attempt is closed.
package scheduler

import (
	"context"
	"errors"
	"fmt"
	"sort"
	"strings"
	"sync"
	"time"
)

// Clock supplies monotonic scheduling time.  Production callers can use
// RealClock; tests should inject a fake Clock instead of sleeping.
type Clock interface {
	Now() time.Time
	After(time.Duration) <-chan time.Time
}

// RealClock is the production clock implementation.
type RealClock struct{}

func (RealClock) Now() time.Time                         { return time.Now() }
func (RealClock) After(d time.Duration) <-chan time.Time { return time.After(d) }

// WaitReason is deliberately closed: it is safe to expose in execution
// events without coupling callers to implementation-specific strings.
type WaitReason string

const (
	WaitInitialPacing  WaitReason = "initial_pacing"
	WaitAdaptivePacing WaitReason = "adaptive_pacing"
	WaitRetryAfter     WaitReason = "retry_after"
	WaitRetryBackoff   WaitReason = "retry_backoff"
	WaitQuotaCapacity  WaitReason = "quota_capacity"
	WaitGlobalCapacity WaitReason = "global_capacity"
	WaitMemoryBudget   WaitReason = "memory_budget"
	WaitDependency     WaitReason = "dependency"
)

var (
	ErrInvalidRequest = errors.New("scheduler: invalid request")
	ErrTooLarge       = errors.New("scheduler: reservation exceeds broker capacity")
	// ErrArtifactBudgetExhausted is terminal: previously committed creations
	// cannot be refunded, so waiting cannot make this request admissible.
	ErrArtifactBudgetExhausted = errors.New("scheduler: artifact budget exhausted")
)

// AdaptiveGroup enables an opt-in, shared additive-increase/multiplicative-
// decrease policy for a group.  It starts with one in-flight request and the
// supplied minimum interval.  MaxCapacity zero inherits Group.Capacity.
//
// It is deliberately separate from Group.Interval so existing static groups
// keep their established capacity and pacing behaviour.
type AdaptiveGroup struct {
	InitialInterval time.Duration
	MaxCapacity     int
}

// Group configures shared pacing and a learned/conservative in-flight limit.
// A zero Capacity inherits the broker capacity; a zero Interval has no pacing.
// Adaptive, when present, replaces those static admission values with its
// learned state.
type Group struct {
	Capacity int
	Interval time.Duration
	Adaptive *AdaptiveGroup
}

// Config is immutable after New.  Group names are safe aliases, never origins.
type Config struct {
	Capacity       int
	MemoryBudget   int64
	ArtifactBudget int
	Groups         map[string]Group
	Clock          Clock
}

// Request describes one physical attempt.  Target and Group are stable safe
// identifiers. ArtifactKey is normally "target/model" and shares a finite
// creation budget between native and SDK work.
type Request struct {
	Target      string
	Group       string
	Weight      int
	MemoryBytes int64
	ArtifactKey string
	Artifacts   int
	// Owner is an opaque, scheduler-safe correlation key for a physical HTTP
	// attempt. The scheduler never interprets it and callers must not use it
	// for opaque/artifact/memory reservations.
	Owner string
	// Reservation distinguishes an observed physical HTTP attempt from an
	// opaque extension invocation or an artifact reservation. Empty retains
	// the physical-attempt default (or artifact for an artifact request).
	Reservation ReservationKind
}

// ReservationKind is scheduler-owned, privacy-safe admission metadata. It
// deliberately identifies resource ownership, not a URL, body, or provider.
type ReservationKind string

const (
	ReservationPhysical ReservationKind = "physical_request"
	ReservationOpaque   ReservationKind = "opaque_reservation"
	ReservationArtifact ReservationKind = "artifact_reservation"
	ReservationMemory   ReservationKind = "memory_reservation"
)

// FactKind is a typed mutation record for an opt-in execution-state bridge.
// Facts are delivered after the scheduler lock has been released.
type FactKind string

const (
	FactRequestQueued     FactKind = "request_queued"
	FactRequestAdmitted   FactKind = "request_admitted"
	FactRequestReleased   FactKind = "request_released"
	FactWaitStarted       FactKind = "wait_started"
	FactWaitUpdated       FactKind = "wait_updated"
	FactWaitEnded         FactKind = "wait_ended"
	FactGroupUpdated      FactKind = "group_updated"
	FactArtifactCommitted FactKind = "artifact_committed"
	FactMemoryReserved    FactKind = "memory_reserved"
	FactMemoryReleased    FactKind = "memory_released"
)

// Fact contains only typed safe identifiers and scheduling facts. Sequence is
// run-local and strictly increasing in broker mutation order. RequestID and
// WaitID are generated by the broker and remain stable across updates.
type Fact struct {
	Sequence    uint64
	Kind        FactKind
	At          time.Time
	RequestID   string
	WaitID      string
	Owner       string
	Target      string
	Group       string
	Reservation ReservationKind
	Reason      WaitReason
	EligibleAt  time.Time
	Capacity    int
	Interval    time.Duration
	Cooldown    time.Time
	Revision    uint64
}

// FactObserver receives facts synchronously after the broker lock is
// released. It must not call this Broker reentrantly; observers should hand
// facts to their own queue when heavier work is required.
type FactObserver func(Fact)

// Event describes a wait lifecycle; it contains no URLs, payloads or tokens.
type Event struct {
	Kind       string // wait_started | wait_ended
	Target     string
	Group      string
	Reason     WaitReason
	At         time.Time
	EligibleAt time.Time
}

// Wait is a live snapshot of a request that has not received a lease.
type Wait struct {
	Target     string
	Group      string
	Reason     WaitReason
	StartedAt  time.Time
	EligibleAt time.Time
}

// Snapshot is suitable for the execution-state reducer.  Waiting does not
// contribute to InFlight.
type Snapshot struct {
	Capacity       int
	InFlight       int
	MemoryBudget   int64
	MemoryReserved int64
	ArtifactBudget int
	Artifacts      map[string]int
	Waiting        []Wait
	Groups         map[string]GroupSnapshot
}

type GroupSnapshot struct {
	InFlight        int
	Capacity        int // configured ceiling; retained for static callers
	LearnedCapacity int
	InitialInterval time.Duration
	Interval        time.Duration
	NextAt          time.Time
	Cooldown        time.Time
	Revision        uint64
}

type Broker struct {
	mu  sync.Mutex
	cfg Config

	inFlight      int
	memory        int64
	groups        map[string]*groupState
	artifacts     map[string]int
	committed     map[string]int
	queue         []*pending
	memoryQueue   []*memoryPending
	events        []Event
	nextID        uint64
	factSequence  uint64
	factQueue     []Fact
	factObservers map[uint64]FactObserver
	nextObserver  uint64
	factMu        sync.RWMutex
	publishMu     sync.Mutex
	publishCond   *sync.Cond
	nextPublish   uint64
	rrTarget      string
	// changed is closed and replaced whenever queue eligibility or capacity
	// changes. Waiters select on it so a request that was previously waiting
	// only for capacity re-reads a newly installed cooldown deadline.
	changed chan struct{}
}

type groupState struct {
	Group
	inFlight         int
	nextAt, cooldown time.Time
	cooldownReason   WaitReason
	learnedCapacity  int
	initialInterval  time.Duration
	revision         uint64
	successStreak    int
	quietWindows     int
}
type pending struct {
	id         uint64
	requestID  string
	waitID     string
	req        Request
	started    time.Time
	result     chan acquireResult
	waitReason WaitReason
	eligibleAt time.Time
	evented    bool
}
type acquireResult struct {
	lease *Lease
	err   error
}

type memoryPending struct {
	id     uint64
	bytes  int64
	result chan memoryResult
}

type memoryResult struct {
	lease *MemoryLease
	err   error
}

// New validates all resource bounds before any request is submitted.
func New(cfg Config) (*Broker, error) {
	if cfg.Capacity < 1 {
		return nil, fmt.Errorf("%w: capacity must be positive", ErrInvalidRequest)
	}
	if cfg.MemoryBudget < 0 || cfg.ArtifactBudget < 0 {
		return nil, fmt.Errorf("%w: budgets must not be negative", ErrInvalidRequest)
	}
	if cfg.Clock == nil {
		cfg.Clock = RealClock{}
	}
	b := &Broker{cfg: cfg, groups: make(map[string]*groupState), artifacts: make(map[string]int), committed: make(map[string]int), changed: make(chan struct{}), nextPublish: 1}
	b.publishCond = sync.NewCond(&b.publishMu)
	for name, group := range cfg.Groups {
		if name == "" || group.Capacity < 0 || group.Interval < 0 {
			return nil, fmt.Errorf("%w: group %q", ErrInvalidRequest, name)
		}
		if group.Capacity == 0 {
			group.Capacity = cfg.Capacity
		}
		state := groupState{Group: group, learnedCapacity: group.Capacity}
		if group.Adaptive != nil {
			adaptive := *group.Adaptive
			if adaptive.InitialInterval <= 0 || adaptive.MaxCapacity < 0 {
				return nil, fmt.Errorf("%w: adaptive group %q", ErrInvalidRequest, name)
			}
			if adaptive.MaxCapacity == 0 {
				adaptive.MaxCapacity = group.Capacity
			}
			if adaptive.MaxCapacity > group.Capacity {
				return nil, fmt.Errorf("%w: adaptive group %q capacity", ErrInvalidRequest, name)
			}
			group.Adaptive = &adaptive
			state.Group = group
			state.learnedCapacity = 1
			state.initialInterval = adaptive.InitialInterval
			state.Interval = adaptive.InitialInterval
		}
		b.groups[name] = &state
	}
	return b, nil
}

// Acquire queues an attempt and returns only after all of its resources were
// granted atomically.  It never occupies a global slot while pacing or another
// resource blocks it.  Context cancellation removes it from the queue.
func (b *Broker) Acquire(ctx context.Context, req Request) (*Lease, error) {
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	b.mu.Lock()
	if err := ctx.Err(); err != nil {
		b.mu.Unlock()
		return nil, err
	}
	if err := b.validateLocked(req); err != nil {
		b.mu.Unlock()
		return nil, err
	}
	p := &pending{id: b.nextID, requestID: fmt.Sprintf("request-%d", b.nextID), waitID: fmt.Sprintf("wait-%d", b.nextID), req: normalise(req), started: b.cfg.Clock.Now(), result: make(chan acquireResult, 1)}
	b.nextID++
	b.queue = append(b.queue, p)
	b.recordFactLocked(Fact{Kind: FactRequestQueued, At: p.started, RequestID: p.requestID, Owner: p.req.Owner, Target: p.req.Target, Group: p.req.Group, Reservation: p.req.Reservation})
	b.scheduleLocked()
	b.signalChangedLocked()
	b.mu.Unlock()
	b.flushFacts()

	for {
		b.mu.Lock()
		wait, hasWait := b.waitForLocked(p)
		changed := b.changed
		b.mu.Unlock()
		if !hasWait { // Result may have been delivered concurrently.
			select {
			case result := <-p.result:
				return result.lease, result.err
			default:
			}
		}
		var timer <-chan time.Time
		if !wait.IsZero() {
			d := wait.Sub(b.cfg.Clock.Now())
			if d < 0 {
				d = 0
			}
			timer = b.cfg.Clock.After(d)
		}
		select {
		case result := <-p.result:
			return result.lease, result.err
		case <-ctx.Done():
			b.mu.Lock()
			removed := b.removeLocked(p)
			if removed {
				if p.evented {
					b.events = append(b.events, Event{Kind: "wait_ended", Target: p.req.Target, Group: p.req.Group, Reason: p.waitReason, At: b.cfg.Clock.Now()})
					b.recordFactLocked(Fact{Kind: FactWaitEnded, At: b.cfg.Clock.Now(), RequestID: p.requestID, WaitID: p.waitID, Owner: p.req.Owner, Target: p.req.Target, Group: p.req.Group, Reservation: p.req.Reservation, Reason: p.waitReason})
				}
				b.scheduleLocked()
				b.signalChangedLocked()
			}
			b.mu.Unlock()
			b.flushFacts()
			if removed {
				return nil, ctx.Err()
			}
			result := <-p.result
			return result.lease, result.err
		case <-timer:
			b.mu.Lock()
			b.scheduleLocked()
			b.signalChangedLocked()
			b.mu.Unlock()
			b.flushFacts()
		case <-changed:
			// A release, cooldown or queue mutation may have changed the next
			// eligible deadline while this waiter had no timer. Re-evaluate it.
		}
	}
}

// ReserveMemory reserves bytes before a caller allocates or serializes a
// request body. It deliberately consumes only MemoryBudget: global and group
// capacity, pacing, and artifact admission do not participate. The returned
// lease must be released when the buffer is no longer retained.
func (b *Broker) ReserveMemory(ctx context.Context, bytes int64) (*MemoryLease, error) {
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	if bytes < 0 {
		return nil, ErrInvalidRequest
	}
	b.mu.Lock()
	if err := ctx.Err(); err != nil {
		b.mu.Unlock()
		return nil, err
	}
	if b.cfg.MemoryBudget > 0 && bytes > b.cfg.MemoryBudget {
		b.mu.Unlock()
		return nil, ErrTooLarge
	}
	p := &memoryPending{id: b.nextID, bytes: bytes, result: make(chan memoryResult, 1)}
	b.nextID++
	b.memoryQueue = append(b.memoryQueue, p)
	b.scheduleLocked()
	b.signalChangedLocked()
	b.mu.Unlock()
	b.flushFacts()

	for {
		b.mu.Lock()
		changed := b.changed
		b.mu.Unlock()
		select {
		case result := <-p.result:
			return result.lease, result.err
		case <-ctx.Done():
			b.mu.Lock()
			removed := b.removeMemoryLocked(p)
			if removed {
				b.scheduleLocked()
				b.signalChangedLocked()
			}
			b.mu.Unlock()
			b.flushFacts()
			if removed {
				return nil, ctx.Err()
			}
			result := <-p.result
			return result.lease, result.err
		case <-changed:
			// A physical or memory lease may have released bytes. Re-evaluate
			// under the broker lock rather than reserving unrelated resources.
		}
	}
}

func normalise(r Request) Request {
	if r.Weight == 0 {
		r.Weight = 1
	}
	if r.Reservation == "" {
		if r.Artifacts > 0 {
			r.Reservation = ReservationArtifact
		} else {
			r.Reservation = ReservationPhysical
		}
	}
	return r
}
func (b *Broker) validateLocked(r Request) error {
	r = normalise(r)
	if r.Target == "" || r.Group == "" || r.Weight < 1 || r.MemoryBytes < 0 || r.Artifacts < 0 || !validReservationKind(r.Reservation) || (r.Owner != "" && !validOwner(r.Owner)) || (r.Reservation != ReservationPhysical && r.Owner != "") {
		return ErrInvalidRequest
	}
	if r.Weight > b.cfg.Capacity || (b.cfg.MemoryBudget > 0 && r.MemoryBytes > b.cfg.MemoryBudget) || (r.Artifacts > 0 && b.cfg.ArtifactBudget == 0) {
		return ErrTooLarge
	}
	groupCapacity := b.cfg.Capacity
	if g := b.groups[r.Group]; g != nil {
		groupCapacity = g.Capacity
	}
	if r.Weight > groupCapacity {
		return ErrTooLarge
	}
	if r.Artifacts > 0 && b.committed[r.ArtifactKey]+r.Artifacts > b.cfg.ArtifactBudget {
		return ErrArtifactBudgetExhausted
	}
	return nil
}

func validOwner(owner string) bool {
	if len(owner) < len("owner-")+16 || len(owner) > 128 || !strings.HasPrefix(owner, "owner-") {
		return false
	}
	for _, r := range owner[len("owner-"):] {
		if !(r >= 'a' && r <= 'f' || r >= '0' && r <= '9') {
			return false
		}
	}
	return true
}

func validReservationKind(kind ReservationKind) bool {
	switch kind {
	case ReservationPhysical, ReservationOpaque, ReservationArtifact:
		return true
	}
	return false
}

// SetFactObserver replaces all subscriptions for backwards compatibility.
// New code that needs to coexist with other consumers should use SubscribeFacts.
// Existing state is intentionally not replayed: callers bind before dispatch
// and use Snapshot for an initial view if needed.
func (b *Broker) SetFactObserver(observer FactObserver) {
	b.factMu.Lock()
	b.factObservers = make(map[uint64]FactObserver)
	if observer != nil {
		b.nextObserver++
		b.factObservers[b.nextObserver] = observer
	}
	b.factMu.Unlock()
}

// SubscribeFacts adds one ordered, opt-in fact consumer and returns an
// idempotent unsubscribe function. A fact fan-out uses a subscription snapshot
// after the broker lock is released, so an unsubscribe affects later facts but
// never truncates delivery halfway through one mutation.
func (b *Broker) SubscribeFacts(observer FactObserver) func() {
	if observer == nil {
		return func() {}
	}
	b.factMu.Lock()
	if b.factObservers == nil {
		b.factObservers = make(map[uint64]FactObserver)
	}
	b.nextObserver++
	id := b.nextObserver
	b.factObservers[id] = observer
	b.factMu.Unlock()
	var once sync.Once
	return func() {
		once.Do(func() {
			b.factMu.Lock()
			delete(b.factObservers, id)
			b.factMu.Unlock()
		})
	}
}

func (b *Broker) recordFactLocked(f Fact) {
	b.factMu.RLock()
	enabled := len(b.factObservers) > 0
	b.factMu.RUnlock()
	if !enabled {
		return
	}
	b.factSequence++
	f.Sequence = b.factSequence
	b.factQueue = append(b.factQueue, f)
}

func (b *Broker) flushFacts() {
	b.mu.Lock()
	facts := append([]Fact(nil), b.factQueue...)
	b.factQueue = nil
	b.mu.Unlock()
	for _, fact := range facts {
		b.publishMu.Lock()
		for fact.Sequence != b.nextPublish {
			b.publishCond.Wait()
		}
		b.factMu.RLock()
		ids := make([]uint64, 0, len(b.factObservers))
		for id := range b.factObservers {
			ids = append(ids, id)
		}
		sort.Slice(ids, func(i, j int) bool { return ids[i] < ids[j] })
		observers := make([]FactObserver, 0, len(ids))
		for _, id := range ids {
			observers = append(observers, b.factObservers[id])
		}
		b.factMu.RUnlock()
		for _, observer := range observers {
			observer(fact)
		}
		b.nextPublish++
		b.publishCond.Broadcast()
		b.publishMu.Unlock()
	}
}

func (b *Broker) recordGroupLocked(name string, g *groupState) {
	b.recordFactLocked(Fact{Kind: FactGroupUpdated, At: b.cfg.Clock.Now(), Group: name, Capacity: g.admissionCapacity(), Interval: g.Interval, Cooldown: g.cooldown, Revision: g.revision})
}

func (b *Broker) groupLocked(name string) *groupState {
	if g := b.groups[name]; g != nil {
		return g
	}
	g := &groupState{Group: Group{Capacity: b.cfg.Capacity}, learnedCapacity: b.cfg.Capacity}
	b.groups[name] = g
	return g
}

// EnsureAdaptiveGroup enables the run-wide learned pacing policy for name.
// It is safe to call repeatedly while targets bind clients before dispatch.
// Multiple clients sharing an alias may have different conservative starting
// intervals; retaining the largest interval and smallest ceiling avoids a
// later binding making an already shared quota more aggressive.
func (b *Broker) EnsureAdaptiveGroup(name string, adaptive AdaptiveGroup) error {
	if name == "" || adaptive.InitialInterval <= 0 || adaptive.MaxCapacity < 0 {
		return ErrInvalidRequest
	}
	b.mu.Lock()
	g := b.groupLocked(name)
	if g.inFlight != 0 {
		b.mu.Unlock()
		return fmt.Errorf("%w: cannot reconfigure active group", ErrInvalidRequest)
	}
	if adaptive.MaxCapacity == 0 || adaptive.MaxCapacity > b.cfg.Capacity {
		adaptive.MaxCapacity = b.cfg.Capacity
	}
	if g.Adaptive != nil {
		if adaptive.InitialInterval > g.initialInterval {
			g.initialInterval = adaptive.InitialInterval
			if g.Interval < adaptive.InitialInterval {
				g.Interval = adaptive.InitialInterval
			}
		}
		if adaptive.MaxCapacity < g.Adaptive.MaxCapacity {
			g.Adaptive.MaxCapacity = adaptive.MaxCapacity
			if g.learnedCapacity > adaptive.MaxCapacity {
				g.learnedCapacity = adaptive.MaxCapacity
			}
		}
		g.revision++
		b.recordGroupLocked(name, g)
		b.signalChangedLocked()
		b.mu.Unlock()
		b.flushFacts()
		return nil
	}
	g.Group = Group{Capacity: b.cfg.Capacity, Adaptive: &adaptive}
	g.learnedCapacity = 1
	g.initialInterval = adaptive.InitialInterval
	g.Interval = adaptive.InitialInterval
	g.revision++
	b.recordGroupLocked(name, g)
	b.signalChangedLocked()
	b.mu.Unlock()
	b.flushFacts()
	return nil
}

func (g *groupState) admissionCapacity() int {
	if g.Adaptive != nil {
		return g.learnedCapacity
	}
	return g.Capacity
}

func (g *groupState) maxAdaptiveCapacity() int {
	if g.Adaptive == nil || g.Adaptive.MaxCapacity == 0 {
		return g.Capacity
	}
	return g.Adaptive.MaxCapacity
}

func (b *Broker) succeededLocked(g *groupState) {
	if g.Adaptive == nil {
		return
	}
	g.successStreak++
	if g.successStreak < 5 {
		return
	}
	g.successStreak = 0
	g.quietWindows++
	if g.Interval > 200*time.Millisecond {
		g.Interval -= 100 * time.Millisecond
		if g.Interval < 200*time.Millisecond {
			g.Interval = 200 * time.Millisecond
		}
	}
	if g.quietWindows >= 2 && g.learnedCapacity < g.maxAdaptiveCapacity() {
		g.learnedCapacity++
		g.quietWindows = 0
	}
	g.revision++
}

func (b *Broker) rateLimitedLocked(g *groupState, retryAfter time.Duration) time.Duration {
	if g.Adaptive == nil {
		if retryAfter > 0 {
			b.applyCooldownLocked(g, b.cfg.Clock.Now().Add(retryAfter), WaitRetryAfter)
		}
		return retryAfter
	}
	g.successStreak, g.quietWindows, g.learnedCapacity = 0, 0, 1
	if g.Interval > 15*time.Second {
		g.Interval = 30 * time.Second
	} else {
		g.Interval *= 2
	}
	source := WaitRetryAfter
	if retryAfter <= 0 {
		retryAfter = g.Interval
		source = WaitAdaptivePacing
	}
	b.applyCooldownLocked(g, b.cfg.Clock.Now().Add(retryAfter), source)
	g.revision++
	return retryAfter
}

func (b *Broker) applyCooldownLocked(g *groupState, until time.Time, source WaitReason) {
	if until.After(g.cooldown) {
		g.cooldown, g.cooldownReason = until, source
	}
	if until.After(g.nextAt) {
		g.nextAt = until
	}
}

// ApplyCooldown prevents new starts in one pacing group only. source must be
// a pacing reason; it is published in snapshots/events of blocked requests.
func (b *Broker) ApplyCooldown(group string, until time.Time, source WaitReason) error {
	if group == "" || (source != WaitRetryAfter && source != WaitRetryBackoff && source != WaitAdaptivePacing) {
		return ErrInvalidRequest
	}
	b.mu.Lock()
	g := b.groupLocked(group)
	if until.After(g.cooldown) {
		g.cooldown, g.cooldownReason = until, source
		g.revision++
		b.recordGroupLocked(group, g)
	}
	b.scheduleLocked()
	b.signalChangedLocked()
	b.mu.Unlock()
	b.flushFacts()
	return nil
}

func (b *Broker) signalChangedLocked() {
	close(b.changed)
	b.changed = make(chan struct{})
}

func (b *Broker) scheduleLocked() {
	for {
		p := b.pickLocked()
		if p != nil {
			b.grantLocked(p)
			continue
		}
		pMemory := b.pickMemoryLocked()
		if pMemory == nil {
			return
		}
		b.grantMemoryLocked(pMemory)
	}
}

func (b *Broker) pickMemoryLocked() *memoryPending {
	for _, p := range b.memoryQueue {
		if b.cfg.MemoryBudget == 0 || b.memory+p.bytes <= b.cfg.MemoryBudget {
			return p
		}
	}
	return nil
}

func (b *Broker) grantMemoryLocked(p *memoryPending) {
	b.memory += p.bytes
	b.removeMemoryLocked(p)
	b.recordFactLocked(Fact{Kind: FactMemoryReserved, At: b.cfg.Clock.Now(), RequestID: fmt.Sprintf("memory-%d", p.id), Reservation: ReservationMemory})
	p.result <- memoryResult{lease: &MemoryLease{broker: b, bytes: p.bytes, id: fmt.Sprintf("memory-%d", p.id)}}
}

func (b *Broker) pickLocked() *pending {
	if len(b.queue) == 0 {
		return nil
	}
	now := b.cfg.Clock.Now()
	targets := make([]string, 0, len(b.queue))
	seen := map[string]bool{}
	for _, p := range b.queue {
		if !seen[p.req.Target] {
			seen[p.req.Target] = true
			targets = append(targets, p.req.Target)
		}
	}
	sort.Strings(targets)
	start := 0
	for i, t := range targets {
		if t > b.rrTarget {
			start = i
			break
		}
		if i == len(targets)-1 {
			start = 0
		}
	}
	for offset := range targets {
		target := targets[(start+offset)%len(targets)]
		for _, p := range b.queue { // stable FIFO within a target
			if p.req.Target != target {
				continue
			}
			reason, eligible, ok := b.admissibleLocked(p, now)
			if !ok {
				b.setWaitLocked(p, reason, eligible)
				break
			}
			b.rrTarget = target
			return p
		}
	}
	return nil
}

func (b *Broker) admissibleLocked(p *pending, now time.Time) (WaitReason, time.Time, bool) {
	g := b.groupLocked(p.req.Group)
	eligible, pacingReason := g.nextAt, WaitInitialPacing
	if !g.cooldown.IsZero() && !g.cooldown.Before(eligible) {
		eligible, pacingReason = g.cooldown, g.cooldownReason
	}
	if eligible.After(now) {
		return pacingReason, eligible, false
	}
	if b.inFlight+p.req.Weight > b.cfg.Capacity {
		return WaitGlobalCapacity, time.Time{}, false
	}
	if g.inFlight+p.req.Weight > g.admissionCapacity() {
		return WaitQuotaCapacity, time.Time{}, false
	}
	if b.cfg.MemoryBudget > 0 && b.memory+p.req.MemoryBytes > b.cfg.MemoryBudget {
		return WaitMemoryBudget, time.Time{}, false
	}
	if p.req.Artifacts > 0 && b.artifacts[p.req.ArtifactKey]+p.req.Artifacts > b.cfg.ArtifactBudget {
		// Artifact creation is a quota-like bounded resource.  The public wait
		// enum intentionally remains the versioned set from the execution
		// contract, so it is represented as quota_capacity rather than a new
		// ad-hoc reason.
		return WaitQuotaCapacity, time.Time{}, false
	}
	return "", time.Time{}, true
}

func (b *Broker) setWaitLocked(p *pending, reason WaitReason, eligible time.Time) {
	if p.waitReason == reason && p.eligibleAt.Equal(eligible) {
		return
	}
	p.waitReason, p.eligibleAt = reason, eligible
	if !p.evented {
		b.events = append(b.events, Event{Kind: "wait_started", Target: p.req.Target, Group: p.req.Group, Reason: reason, At: b.cfg.Clock.Now(), EligibleAt: eligible})
		b.recordFactLocked(Fact{Kind: FactWaitStarted, At: b.cfg.Clock.Now(), RequestID: p.requestID, WaitID: p.waitID, Owner: p.req.Owner, Target: p.req.Target, Group: p.req.Group, Reservation: p.req.Reservation, Reason: reason, EligibleAt: eligible})
		p.evented = true
	} else {
		b.recordFactLocked(Fact{Kind: FactWaitUpdated, At: b.cfg.Clock.Now(), RequestID: p.requestID, WaitID: p.waitID, Owner: p.req.Owner, Target: p.req.Target, Group: p.req.Group, Reservation: p.req.Reservation, Reason: reason, EligibleAt: eligible})
	}
}

func (b *Broker) grantLocked(p *pending) {
	g := b.groupLocked(p.req.Group)
	b.inFlight += p.req.Weight
	b.memory += p.req.MemoryBytes
	g.inFlight += p.req.Weight
	if g.Interval > 0 {
		g.nextAt = b.cfg.Clock.Now().Add(g.Interval)
		g.revision++
		b.recordGroupLocked(p.req.Group, g)
	}
	if p.req.Artifacts > 0 {
		b.artifacts[p.req.ArtifactKey] += p.req.Artifacts
	}
	b.removeLocked(p)
	if p.evented {
		b.events = append(b.events, Event{Kind: "wait_ended", Target: p.req.Target, Group: p.req.Group, Reason: p.waitReason, At: b.cfg.Clock.Now()})
		b.recordFactLocked(Fact{Kind: FactWaitEnded, At: b.cfg.Clock.Now(), RequestID: p.requestID, WaitID: p.waitID, Owner: p.req.Owner, Target: p.req.Target, Group: p.req.Group, Reservation: p.req.Reservation, Reason: p.waitReason})
	}
	b.recordFactLocked(Fact{Kind: FactRequestAdmitted, At: b.cfg.Clock.Now(), RequestID: p.requestID, Owner: p.req.Owner, Target: p.req.Target, Group: p.req.Group, Reservation: p.req.Reservation})
	p.result <- acquireResult{lease: &Lease{broker: b, req: p.req, id: p.requestID}}
}

func (b *Broker) removeLocked(p *pending) bool {
	for i, q := range b.queue {
		if q == p {
			b.queue = append(b.queue[:i], b.queue[i+1:]...)
			return true
		}
	}
	return false
}

func (b *Broker) removeMemoryLocked(p *memoryPending) bool {
	for i, q := range b.memoryQueue {
		if q == p {
			b.memoryQueue = append(b.memoryQueue[:i], b.memoryQueue[i+1:]...)
			return true
		}
	}
	return false
}

func (b *Broker) waitForLocked(p *pending) (time.Time, bool) {
	for _, q := range b.queue {
		if q == p {
			return q.eligibleAt, true
		}
	}
	return time.Time{}, false
}

// Lease holds all resources granted to one physical attempt.
type Lease struct {
	broker       *Broker
	req          Request
	id           string
	once         sync.Once
	feedbackOnce sync.Once
}

// MemoryLease holds only a MemoryBudget reservation. Release is idempotent.
type MemoryLease struct {
	broker *Broker
	bytes  int64
	id     string
	once   sync.Once
}

func (l *MemoryLease) Release() {
	l.once.Do(func() {
		b := l.broker
		b.mu.Lock()
		b.memory -= l.bytes
		b.recordFactLocked(Fact{Kind: FactMemoryReleased, At: b.cfg.Clock.Now(), RequestID: l.id, Reservation: ReservationMemory})
		b.scheduleLocked()
		b.signalChangedLocked()
		b.mu.Unlock()
		b.flushFacts()
	})
}

// Release is idempotent and must be called after body EOF/Close or cancellation.
// An artifact-bearing lease is thereafter treated as committed: only
// CancelBeforeDispatch can prove that no remote creation was attempted.
func (l *Lease) Release() { l.release(false) }

// Succeeded reports a quiet successful attempt before Release.  For an
// adaptive group, five successes tighten the interval and every second quiet
// window raises its learned in-flight limit by one, up to its configured cap.
// Calling it for a static group is harmless.
func (l *Lease) Succeeded() {
	l.feedbackOnce.Do(func() {
		b := l.broker
		b.mu.Lock()
		b.succeededLocked(b.groupLocked(l.req.Group))
		b.recordGroupLocked(l.req.Group, b.groupLocked(l.req.Group))
		b.scheduleLocked()
		b.signalChangedLocked()
		b.mu.Unlock()
		b.flushFacts()
	})
}

// RateLimited reports a 429 before Release, atomically revising the shared
// group's learned limit, pacing interval and cooldown.  A non-positive
// retryAfter uses the newly increased interval as a deterministic cooldown.
// It returns the applied cooldown duration for transport telemetry.
func (l *Lease) RateLimited(retryAfter time.Duration) time.Duration {
	var applied time.Duration
	l.feedbackOnce.Do(func() {
		b := l.broker
		b.mu.Lock()
		applied = b.rateLimitedLocked(b.groupLocked(l.req.Group), retryAfter)
		b.recordGroupLocked(l.req.Group, b.groupLocked(l.req.Group))
		b.scheduleLocked()
		b.signalChangedLocked()
		b.mu.Unlock()
		b.flushFacts()
	})
	return applied
}

// CancelBeforeDispatch releases the lease and refunds an artifact reservation.
// It is only valid before a remote creation could have been initiated.
func (l *Lease) CancelBeforeDispatch() { l.release(true) }
func (l *Lease) release(refundArtifacts bool) {
	l.once.Do(func() {
		b := l.broker
		b.mu.Lock()
		b.inFlight -= l.req.Weight
		b.memory -= l.req.MemoryBytes
		b.groupLocked(l.req.Group).inFlight -= l.req.Weight
		if refundArtifacts && l.req.Artifacts > 0 {
			b.artifacts[l.req.ArtifactKey] -= l.req.Artifacts
			if b.artifacts[l.req.ArtifactKey] == 0 {
				delete(b.artifacts, l.req.ArtifactKey)
			}
		} else if l.req.Artifacts > 0 {
			b.committed[l.req.ArtifactKey] += l.req.Artifacts
			b.recordFactLocked(Fact{Kind: FactArtifactCommitted, At: b.cfg.Clock.Now(), RequestID: l.id, Owner: l.req.Owner, Target: l.req.Target, Group: l.req.Group, Reservation: l.req.Reservation})
		}
		b.recordFactLocked(Fact{Kind: FactRequestReleased, At: b.cfg.Clock.Now(), RequestID: l.id, Owner: l.req.Owner, Target: l.req.Target, Group: l.req.Group, Reservation: l.req.Reservation})
		b.scheduleLocked()
		b.signalChangedLocked()
		b.mu.Unlock()
		b.flushFacts()
	})
}

// Snapshot returns a copy, ordered deterministically for renderers and tests.
func (b *Broker) Snapshot() Snapshot {
	b.mu.Lock()
	defer b.mu.Unlock()
	s := Snapshot{Capacity: b.cfg.Capacity, InFlight: b.inFlight, MemoryBudget: b.cfg.MemoryBudget, MemoryReserved: b.memory, ArtifactBudget: b.cfg.ArtifactBudget, Artifacts: make(map[string]int), Groups: make(map[string]GroupSnapshot)}
	for k, v := range b.artifacts {
		s.Artifacts[k] = v
	}
	for k, g := range b.groups {
		s.Groups[k] = GroupSnapshot{InFlight: g.inFlight, Capacity: g.Capacity, LearnedCapacity: g.admissionCapacity(), InitialInterval: g.initialInterval, Interval: g.Interval, NextAt: g.nextAt, Cooldown: g.cooldown, Revision: g.revision}
	}
	for _, p := range b.queue {
		s.Waiting = append(s.Waiting, Wait{Target: p.req.Target, Group: p.req.Group, Reason: p.waitReason, StartedAt: p.started, EligibleAt: p.eligibleAt})
	}
	sort.Slice(s.Waiting, func(i, j int) bool {
		if s.Waiting[i].Target != s.Waiting[j].Target {
			return s.Waiting[i].Target < s.Waiting[j].Target
		}
		return s.Waiting[i].Group < s.Waiting[j].Group
	})
	return s
}

// Events returns a copy of wait lifecycle events in their deterministic
// broker order.  A later typed execution bus can consume these without a
// callback under the scheduler lock.
func (b *Broker) Events() []Event {
	b.mu.Lock()
	defer b.mu.Unlock()
	return append([]Event(nil), b.events...)
}
